from sqlalchemy import Column, Integer, String, DateTime, Boolean, Text, JSON
from datetime import datetime
from app.db.database import Base


class DeviceSecurityProfile(Base):
    """
    Stores the security posture and calculated risk score for each device.
    Lives in Policy Service — owned by the risk/compliance domain.
    device_id is a logical reference; no FK enforced (device owned by Asset Service).
    """
    __tablename__ = "device_security_profiles"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, unique=True, nullable=False, index=True)

    # ── Security Flags (derived from compliance violations + agent reports) ──
    is_rooted = Column(Boolean, default=False)
    encryption_enabled = Column(Boolean, default=True)
    screen_lock_enabled = Column(Boolean, default=True)
    os_outdated = Column(Boolean, default=False)
    blacklisted_app_detected = Column(Boolean, default=False)

    # ── Calculated Risk ───────────────────────────────────────────────────────
    risk_score = Column(Integer, default=0)
    risk_level = Column(String, default="low")  # low | medium | high | critical

    last_evaluated_at = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)
    updated_at = Column(DateTime, default=datetime.utcnow, onupdate=datetime.utcnow)


class SecurityAlert(Base):
    """
    Threat alerts generated by the risk engine during security evaluation.
    One alert per distinct threat type per evaluation run.
    """
    __tablename__ = "security_alerts"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, nullable=False, index=True)

    alert_type = Column(String, nullable=False)   # rooted_device | encryption_disabled | …
    severity = Column(String, nullable=False)      # critical | high | medium | low
    message = Column(Text, nullable=False)
    status = Column(String, default="open")        # open | resolved | suppressed
    acknowledged_by = Column(String, nullable=True)
    resolved_at = Column(DateTime, nullable=True)
    created_at = Column(DateTime, default=datetime.utcnow)


class RemediationAction(Base):
    """
    Tracks remediation actions taken against a security alert or compliance violation.
    """
    __tablename__ = "remediation_actions"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, nullable=False, index=True)
    alert_id = Column(Integer, nullable=True)

    action_type = Column(String, nullable=False)   # manual_fix | policy_push | wipe | lock | note
    performed_by = Column(String, default="admin")
    notes = Column(Text, default="")
    status = Column(String, default="pending")     # pending | in_progress | completed | failed
    created_at = Column(DateTime, default=datetime.utcnow)
    completed_at = Column(DateTime, nullable=True)


class DeviceCommand(Base):
    """
    Remote commands dispatched to a device through the MDM system.
    The agent polls for pending commands and reports back execution results.
    """
    __tablename__ = "device_commands"

    id = Column(Integer, primary_key=True, index=True)
    device_id = Column(Integer, nullable=False, index=True)

    # Command type: lock | wipe | restart | sync | message | clear_passcode | enable_lost_mode
    command_type = Column(String, nullable=False)

    # pending → sent → acknowledged → completed | failed | cancelled
    status = Column(String, default="pending")

    # Optional JSON payload (e.g. {"message": "Hello"} for send_message)
    payload = Column(JSON, default=dict)

    # Who issued the command
    issued_by = Column(String, default="admin")

    created_at = Column(DateTime, default=datetime.utcnow)
    executed_at = Column(DateTime, nullable=True)

    # Raw response back from the device agent
    response = Column(Text, nullable=True)
